export const LanguageContext = createContext<"en" | "ar">("en");
export function useT() {
  const lang = useContext(LanguageContext);
  return (key: string) =>
    ((lang === "ar" ? ar : en) as Record<string, string>)[key] || key;
}
export function date(value: string | null, lang = "en") {
  return value
    ? new Intl.DateTimeFormat(lang === "ar" ? "ar-EG" : "en-GB", {
        dateStyle: "medium",
        timeStyle: "medium",
        timeZone: "UTC",
      }).format(new Date(value)) + " UTC"
    : "—";
}
export function number(value: number | null, unit = "", digits = 1) {
  return value === null || !Number.isFinite(value)
    ? "—"
    : new Intl.NumberFormat("en", { maximumFractionDigits: digits }).format(
        value,
      ) + (unit ? " " + unit : "");
}
